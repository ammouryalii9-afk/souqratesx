const translations = { en, ar, es, ru } as const;

export type Lang = 'en' | 'ar' | 'es' | 'ru';
export type Tr = typeof en;

const LANG_CYCLE: Record<Lang, Lang> = { en: 'ar', ar: 'es', es: 'ru', ru: 'en' };

interface LangCtx {
  lang: Lang;
  toggleLang: () => void;
  tr: Tr;
}

const LanguageContext = createContext<LangCtx>({
  lang: 'en',
  toggleLang: () => {},
  tr: en,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      const valid: Lang[] = ['en', 'ar', 'es', 'ru'];
      return valid.includes(saved as Lang) ? (saved as Lang) : 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    try { localStorage.setItem(LANG_KEY, lang); } catch {}
  }, [lang]);

  const toggleLang = () => setLang(l => LANG_CYCLE[l]);
  const tr = translations[lang] as Tr;

  return (
    <LanguageContext.Provider value={{ lang, toggleLang, tr }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
